async (page) => {
  await page.goto('http://127.0.0.1:3008/?scenario=upload-error#/image-processing/text');
  await page.reload();
  await page.getByRole('heading',{name:'替换文字',exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles('output/playwright/pixel.png');
  await page.getByRole('button',{name:'重试图片 1',exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'提交生成任务'}).isDisabled()) throw new Error('上传失败仍能提交');
  await page.getByRole('button',{name:'重试图片 1',exact:true}).click();
  await page.getByText('模拟已接收',{exact:true}).waitFor();
  await page.getByRole('button',{name:'移除图片 1',exact:true}).click();
  if(await page.getByText('模拟已接收',{exact:true}).count()) throw new Error('移除失败');
  await page.locator('input[type=file]').setInputFiles('output/playwright/pixel.png');
  await page.getByText('模拟已接收',{exact:true}).waitFor();
  await page.getByRole('button',{name:'移除图片 1',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles('output/playwright/invalid.png');
  await page.getByText('无法解码图片，请选择完整的 JPG、PNG 或 WebP 文件',{exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'提交生成任务'}).isDisabled()) throw new Error('损坏图片仍能提交');
  await page.getByRole('button',{name:'移除图片 1',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles('output/playwright/empty.png');
  await page.getByText('empty.png：文件为空，请选择有内容的图片',{exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles('output/playwright/too-large.png');
  await page.getByText('too-large.png：单张图片不能超过 10 MiB',{exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles('output/playwright/wrong.svg');
  await page.getByText('wrong.svg：仅支持 JPG、PNG、WebP 图片',{exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles(Array(21).fill('output/playwright/pixel.png'));
  await page.getByText('pixel.png：每组最多 20 张，请移除图片后再添加',{exact:true}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.picture-meta small').length===20 && Array.from(document.querySelectorAll('.picture-meta small')).every(x=>x.textContent==='模拟已接收'));
  await page.screenshot({path:'output/playwright/phase2-upload.png',fullPage:true});
  await page.goto('http://127.0.0.1:3008/?scenario=submit-error#/image-processing/text');
  await page.getByRole('button',{name:'使用示例素材'}).click();
  await page.getByRole('textbox',{name:'任务名称',exact:true}).fill('重试任务保留');
  await page.getByRole('button',{name:'提交生成任务'}).click();
  await page.getByRole('alert').filter({hasText:'模拟服务本次接收失败'}).first().waitFor();
  if(await page.getByRole('textbox',{name:'任务名称',exact:true}).inputValue()!=='重试任务保留') throw new Error('失败丢失输入');
  if(await page.getByText('模拟已接收',{exact:true}).count()!==2) throw new Error('失败丢失素材');
  await page.getByRole('button',{name:'提交生成任务'}).click();
  await page.getByRole('dialog',{name:'重试任务保留',exact:true}).waitFor();
  return 'PASS 上传失败重试/移除/同文件重选、解码失败、空/超10MiB/类型错误、21张截到20张、提交失败保留后重试';
}
