// 仅供交互预览；固定规则不包含示例图片对象或具体修改要求。
const USER_INSTRUCTIONS = '{{用户本次填写的修改意见及各处标注说明}}'
export const IMAGE_EDIT_TEMPLATE = `【任务】
以用户选定的无标注图片为编辑底图，根据本次修改意见和可选标注完成指定的局部图像编辑。

【编辑范围】
1. 具体修改对象、位置、目标效果均以本次用户意见为准，不预设图片类型、对象类别或修改目标。
2. 仅执行用户明确要求的操作；可按要求调整位置、大小、形状、颜色、材质或局部细节，也可替换、添加或移除指定元素。未要求的操作不执行。
3. 修改仅限指定对象及完成编辑必需的邻近区域。未指定修改的其他元素、文字、背景、构图和布局保持原样，不擅自美化或重新设计整图。

【局部融合】
1. 根据具体操作处理受影响区域：移动、替换或移除元素时清除不应保留的旧内容，自然补全原位置；添加或调整元素时保持边缘衔接自然。
2. 除用户明确要求改变的属性外，保持与所在画面的透视、比例、光照、阴影、纹理和风格协调，避免残留、重影、接缝及多余元素。
3. 位置与方向按用户明确指定的参照对象理解。不擅自猜测不明确的修改对象、目标位置或效果；无法确定的部分保留原样。

【标注使用】
标注图仅用于定位和对应各处修改意见，以无标注图片作为编辑底图。
新增的框、圈线、箭头、笔迹和编号不进入成品；底图原有的正常图文元素不因外观类似标注而被删除。
未提供标注时，根据用户明确描述定位；标注范围不代表允许随意重绘其中所有内容。

【用户修改意见】
${USER_INSTRUCTIONS}

【输出要求】
只输出一张修改后的完整图片，保持原图尺寸及画幅，不输出解释、对比拼图或标注图。`

export function buildImageEditPrompt(text: string): string {
  return IMAGE_EDIT_TEMPLATE.replace(USER_INSTRUCTIONS, () => text)
}
