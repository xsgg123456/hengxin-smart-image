import assert from 'node:assert/strict'
import { resolve } from 'node:path'

export async function verifyManagedViewer({ page, output, checks, calls, root, waitName, refresh, setFailure, setLongContent }) {
  const button = name => page.getByRole('button', { name, exact: true })
  const viewer = page.locator('.el-image-viewer__wrapper'), caption = viewer.locator('.image-caption')
  const messages = page.locator('.wm-messages')
  const choose = id => page.locator('.wm-conversation').filter({ has: page.getByText(`验收会话 ${id}`, { exact: true }) }).click()
  const open = async name => { await page.locator('.wm-messages').getByRole('button', { name: `预览 ${name}`, exact: true }).click(); await viewer.waitFor() }
  const loaded = async () => { await page.waitForFunction(() => [...document.querySelectorAll('.el-image-viewer__img')].some(img => getComputedStyle(img).display !== 'none' && img.complete && img.naturalWidth > 1 && img.src.startsWith('blob:'))); await page.waitForTimeout(350) }
  const closed = async () => { await page.keyboard.press('Escape'); await viewer.waitFor({ state: 'hidden' }) }
  const inViewport = async locator => assert.ok(await locator.evaluate(el => { const r = el.getBoundingClientRect(); return r.width > 0 && r.left >= -1 && r.right <= innerWidth + 1 && r.top >= -1 && r.bottom <= innerHeight + 1 }))
  await button('展开').click()
  await inViewport(button('退出展开')); await inViewport(page.locator('.wm-readonly'))
  assert.deepEqual(await page.locator('.wm-task-workspace.expanded').evaluate(el => { const r = el.getBoundingClientRect(); return [r.x, r.y, r.width, r.height] }), [0, 0, 1920, 1080])
  await page.screenshot({ path: resolve(output, 'viewer-expanded-desktop.png'), fullPage: true })
  await choose(1); await waitName(1); await button('退出展开').waitFor()
  await choose(0); await waitName(0)
  const countBefore = calls.filter(call => call.path === `${root}/session-0`).length
  await button('退出展开').click(); await button('展开').click()
  assert.equal(calls.filter(call => call.path === `${root}/session-0`).length, countBefore, '展开切换不重新加载会话')
  await open('已保存图片.png'); await loaded()
  assert.match(await caption.innerText(), /生成结果 · 1 \/ 3/)
  await page.keyboard.press('ArrowRight'); await loaded(); assert.match(await caption.innerText(), /第二张图片.png/)
  await page.keyboard.press('ArrowRight'); await loaded(); assert.match(await caption.innerText(), /图片输出.png/)
  await page.keyboard.press('ArrowLeft'); await loaded(); assert.match(await caption.innerText(), /2 \/ 3/)
  const image = viewer.locator('.el-image-viewer__img:visible'), before = await image.evaluate(el => el.style.transform)
  await image.hover(); await page.mouse.wheel(0, -300); await page.waitForTimeout(200)
  assert.notEqual(await image.evaluate(el => el.style.transform), before, '滚轮缩放')
  const box = await image.boundingBox(), zoomed = await image.evaluate(el => el.style.transform)
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 45, box.y + box.height / 2 + 30, { steps: 5 }); await page.mouse.up()
  assert.notEqual(await image.evaluate(el => el.style.transform), zoomed, '原图拖动')
  const downloading = page.waitForEvent('download'); await caption.getByRole('button', { name: '下载原图' }).click()
  assert.equal((await downloading).suggestedFilename(), '第二张图片.png')
  await page.screenshot({ path: resolve(output, 'viewer-image-desktop.png') }); await closed()
  const position = await messages.evaluate(el => el.scrollTop)
  await open('已保存图片.png'); await loaded(); await closed()
  assert.equal(await messages.evaluate(el => el.scrollTop), position, '关图后阅读位置保持')
  setLongContent(true); await refresh()
  await page.waitForFunction(() => document.querySelector('.wm-messages')?.textContent.includes('阅读位置验证'))
  await messages.evaluate(el => { el.scrollTop = 120; el.dispatchEvent(new Event('scroll')) })
  await button('退出展开').click(); assert.equal(await messages.evaluate(el => el.scrollTop), 120)
  await button('展开').click(); assert.equal(await messages.evaluate(el => el.scrollTop), 120)
  setLongContent(false); await refresh()
  await page.waitForFunction(() => !document.querySelector('.wm-messages')?.textContent.includes('阅读位置验证'))
  const reference = messages.getByRole('button', { name: '预览 参考图片.png', exact: true })
  await reference.focus(); await page.keyboard.press('Space'); await loaded(); assert.match(await caption.innerText(), /用户附件 · 1 \/ 2/); await closed()
  await reference.focus(); await page.keyboard.press('Enter'); await loaded(); await closed()
  await button('附件与结果').click()
  const drawer = page.getByRole('dialog')
  await drawer.getByRole('tab', { name: '生成结果', exact: true }).click()
  await drawer.getByRole('button', { name: '预览 图片输出.png', exact: true }).click(); await loaded()
  assert.match(await caption.innerText(), /生成结果 · 3 \/ 3/)
  assert.ok(await viewer.evaluate(el => { const r = document.querySelector('.image-caption').getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + 5, r.y + 5)) }), '查看器位于抽屉上层')
  await closed(); assert.ok(await drawer.isVisible()); await page.keyboard.press('Escape'); await drawer.waitFor({ state: 'hidden' })
  // API原图失败后可原位重试，管理GET仍逐次核权。
  setFailure(503); await open('已保存图片.png'); await viewer.locator('.image-cache-error').waitFor()
  setFailure(0); await viewer.getByRole('button', { name: '重新加载' }).click(); await loaded(); await closed()
  await refresh()
  for (const width of [1000, 390]) {
    await page.setViewportSize({ width, height: 844 })
    await inViewport(button('退出展开')); await inViewport(button('刷新会话')); await inViewport(page.locator('.wm-readonly'))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: resolve(output, `viewer-expanded-${width}.png`) })
    await open('第二张图片.png'); await loaded(); await inViewport(caption.getByRole('button', { name: '下载原图' }))
    await page.screenshot({ path: resolve(output, `viewer-image-${width}.png`) }); await closed()
  }
  await page.setViewportSize({ width: 1920, height: 1080 })
  await open('已保存图片.png'); await loaded(); setFailure(403); await page.keyboard.press('ArrowRight')
  await page.getByText('无权查看任务', { exact: true }).waitFor()
  assert.equal(await viewer.count(), 0); assert.equal(await page.locator('.wm-managed-asset,.wm-chat').count(), 0)
  setFailure(0); await page.reload(); await waitName(0)
  checks.push('展开/退出无重载、同任务切会话保持展开；3图组左右/缩放/拖动/原图下载、附件组键盘打开、抽屉层级及Esc返回、503重试、预览403清空、桌面/1000/390布局')
}
